-- ====================================================================
-- PARTE 0: LIMPEZA DE OBJETOS PREEXISTENTES (DROP SEGURO E IDEMPOTENTE)
-- ====================================================================

BEGIN
    -- Drop seguro de tabelas com remoção em cascata de constraints
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDITORIA_DML_CHAMADO', 'HIST_CHAMADO', 'HIST_CHAMADOS', 'HIST_STATUS',
        'VOTO_CHAMADO', 'CHAMADO', 'STATUS', 'CATEGORIA', 'TELEFONE',
        'USUARIO', 'ENDERECO', 'BAIRRO', 'CIDADE', 'ESTADO'
    )) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
            DBMS_OUTPUT.PUT_LINE('Tabela removida: ' || t.table_name);
        EXCEPTION
            WHEN OTHERS THEN
                DBMS_OUTPUT.PUT_LINE('Aviso ao remover tabela ' || t.table_name || ': ' || SQLERRM);
        END;
    END LOOP;

    -- Drop seguro de pacotes relacionados ao ZelaFix
    FOR p IN (SELECT object_name, object_type FROM user_objects 
               WHERE object_name IN ('PKG_CHAMADO_GESTAO', 'PKG_ENGAJAMENTO_CIDADAO', 'PKG_ZELAFIX', 'PKG_AUDITORIA_ZELAFIX') 
                 AND object_type = 'PACKAGE') LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP ' || p.object_type || ' ' || p.object_name;
            DBMS_OUTPUT.PUT_LINE('Objeto removido: ' || p.object_type || ' ' || p.object_name);
        EXCEPTION
            WHEN OTHERS THEN
                DBMS_OUTPUT.PUT_LINE('Aviso ao remover ' || p.object_type || ' ' || p.object_name || ': ' || SQLERRM);
        END;
    END LOOP;
END;
